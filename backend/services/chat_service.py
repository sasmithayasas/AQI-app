def generate_gemini_response(api_key: str, system_prompt: str, user_message: str, history: Optional[List[Dict]] = None) -> str:
    """
    Calls Google Gemini REST API across available model versions.
    """
    contents = []
    
    # System instruction (or prime message)
    contents.append({
        "role": "user",
        "parts": [{"text": f"System Instructions:\n{system_prompt}\n\nPlease acknowledge and wait for my questions."}]
    })
    contents.append({
        "role": "model",
        "parts": [{"text": "Understood. I am SentinelAI, ready to assist with real-time air quality and health guidance grounded in live SentinelAQ and global atmospheric telemetry."}]
    })

    # Append conversation history
    if history:
        for msg in history[-6:]:  # Keep last 3 turns
            role = "user" if msg.get("role") == "user" else "model"
            contents.append({
                "role": role,
                "parts": [{"text": msg.get("content", "")}]
            })

    # Current user message
    contents.append({
        "role": "user",
        "parts": [{"text": user_message}]
    })

    payload = {
        "contents": contents,
        "generationConfig": {
            "temperature": 0.4,
            "maxOutputTokens": 1500,
            "topP": 0.95
        }
    }

    last_error = None
    for model_name in GEMINI_MODELS:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{model_name}:generateContent?key={api_key}"
        req = urllib.request.Request(
            url,
            data=json.dumps(payload).encode("utf-8"),
            headers={
                "Content-Type": "application/json",
                "x-goog-api-key": api_key
            }
        )

        try:
            with urllib.request.urlopen(req, timeout=10) as response:
                res_data = json.loads(response.read().decode("utf-8"))
                candidates = res_data.get("candidates", [])
                if candidates:
                    parts = candidates[0].get("content", {}).get("parts", [])
                    if parts:
                        raw_text = parts[0].get("text", "").strip()
                        return clean_latex_formatting(raw_text)
        except urllib.error.HTTPError as e:
            last_error = f"HTTP {e.code} on {model_name}: {e.read().decode('utf-8')}"
            continue
        except Exception as e:
            last_error = str(e)
            continue

    raise RuntimeError(f"All Gemini models failed. Last error: {last_error}")


