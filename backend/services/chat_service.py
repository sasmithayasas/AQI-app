def _load_env_fallback():
    for env_path in [".env", "backend/.env", "../.env", "/root/aqi-backend/backend/.env"]:
        if os.path.exists(env_path):
            try:
                with open(env_path, "r", encoding="utf-8") as f:
                    for line in f:
                        line = line.strip()
                        if line and not line.startswith("#") and "=" in line:
                            k, v = line.split("=", 1)
                            k = k.strip()
                            v = v.strip().strip('"').strip("'")
                            if k and k not in os.environ:
                                os.environ[k] = v
            except Exception:
                pass


def answer_user_query(user_message: str, telemetry: Dict, city: str = "kandy", lang: str = "en", history: Optional[List[Dict]] = None) -> Dict:
    """
    Main entry point for conversational air quality queries.
    Dynamically ingests global atmospheric telemetry for world cities.
    Tries Google Gemini LLM first; gracefully falls back to intelligent rule-based engine.
    """
    # 1. Check if user is asking about an international/global world city (including acronyms like LA, NYC, SF)
    global_telemetry = None
    target_city = extract_global_city(user_message)
    if target_city:
        global_telemetry = fetch_live_global_aqi(target_city)

    # 2. Read API Key from environment variable (or .env fallback)
    _load_env_fallback()
    api_key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")

    if api_key and len(api_key.strip()) > 10:
        try:
            system_prompt = build_system_prompt(telemetry, city, lang, global_telemetry)
            reply_text = generate_gemini_response(api_key.strip(), system_prompt, user_message, history)
            return {
                "source": "gemini_llm",
                "city": city,
                "lang": lang,
                "global_data": global_telemetry,
                "reply": clean_latex_formatting(reply_text)
            }
        except Exception as e:
            print(f"[SentinelAI] Gemini API error: {e}. Falling back to rule-based engine.")

    # 3. Rule-based fallback (with real-time global telemetry if available)
    reply_text = fallback_rule_based_response(user_message, telemetry, city, lang, global_telemetry)
    return {
        "source": "sentinel_ai_engine",
        "city": city,
        "lang": lang,
        "global_data": global_telemetry,
        "reply": clean_latex_formatting(reply_text)
    }
