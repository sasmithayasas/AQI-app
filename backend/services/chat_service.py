def clean_latex_formatting(text: str) -> str:
    r"""
    Sanitizes raw LaTeX mathematical notation generated by LLMs into clean, human-readable Unicode text.
    Transforms $\text{NO}_2$ -> NO₂, $\text{PM}_{2.5}$ -> PM2.5, $\mu\text{g/m}^3$ -> µg/m³, $102\text{ ppb}$ -> 102 ppb.
    """
    if not text:
        return ""

    # 1. Standard chemical formulas in LaTeX
    text = re.sub(r"\$\\text\{PM\}\_?\{?2\.5\}?\$|\$\\text\{PM2\.5\}\$", "PM2.5", text, flags=re.IGNORECASE)
    text = re.sub(r"\$\\text\{PM\}\_?\{?10\}?\$|\$\\text\{PM10\}\$", "PM10", text, flags=re.IGNORECASE)
    text = re.sub(r"\$\\text\{NO\}\_?\{?2\}?\$|\$\\text\{NO2\}\$", "NO₂", text, flags=re.IGNORECASE)
    text = re.sub(r"\$\\text\{O\}\_?\{?3\}?\$|\$\\text\{O3\}\$", "O₃", text, flags=re.IGNORECASE)
    text = re.sub(r"\$\\text\{SO\}\_?\{?2\}?\$|\$\\text\{SO2\}\$", "SO₂", text, flags=re.IGNORECASE)
    text = re.sub(r"\$\\text\{CO\}\$", "CO", text, flags=re.IGNORECASE)
    text = re.sub(r"\$\\text\{CO\}\_?\{?2\}?\$|\$\\text\{CO2\}\$", "CO₂", text, flags=re.IGNORECASE)

    # 2. Units (µg/m³, ppb, ppm)
    text = re.sub(r"\$\\\\mu\\text\{g/m\}\^\{?3\}?\$|\$\\mu\\text\{g/m\}\^\{?3\}?\$", "µg/m³", text)
    text = re.sub(r"\$\\\\mu\\text\{g\}/\\text\{m\}\^\{?3\}?\$|\$\\mu\\text\{g\}/\\text\{m\}\^\{?3\}?\$", "µg/m³", text)
    text = re.sub(r"\$\\mu\s*g/m\^?3\$|\\mu\s*g/m\^?3", "µg/m³", text, flags=re.IGNORECASE)
    text = re.sub(r"\\mu\s*g", "µg", text)

    # 3. Numeric LaTeX units: $102.0\text{ ppb}$ -> 102.0 ppb
    text = re.sub(r"\$([0-9\.\s\-]+)\\text\{([^}]+)\}\$", r"\1 \2", text)
    text = re.sub(r"\$([0-9\.\s\-]+)\s*\\mu\s*g/m\^?3\$", r"\1 µg/m³", text)

    # 4. Generic \text{...} wrappers
    text = re.sub(r"\$\\text\{([^}]+)\}\$", r"\1", text)
    text = re.sub(r"\\text\{([^}]+)\}", r"\1", text)

    # 5. Clean remaining inline math dollar signs around plain text/numbers: $85\text{ (Moderate)}$ -> 85 (Moderate)
    text = re.sub(r"\$([^\$]+)\$", r"\1", text)

    # 6. Normalize Unicode subscripts
    text = re.sub(r"\bPM_2\.5\b", "PM2.5", text)
    text = re.sub(r"\bPM_10\b", "PM10", text)
    text = re.sub(r"\bNO_2\b", "NO₂", text)
    text = re.sub(r"\bO_3\b", "O₃", text)
    text = re.sub(r"\bSO_2\b", "SO₂", text)
    text = re.sub(r"\bCO_2\b", "CO₂", text)

    return text


def get_aqi_category(aqi: int) -> str:
    if aqi <= 50:
        return "Good"
    elif aqi <= 100:
        return "Moderate"
    elif aqi <= 150:
        return "Unhealthy for Sensitive Groups"
    elif aqi <= 200:
        return "Unhealthy"
    elif aqi <= 300:
        return "Very Unhealthy"
    else:
        return "Hazardous"


def extract_global_city(query: str) -> Optional[str]:
    """
    Extracts a candidate world city from user message.
    Supports acronyms like 'LA', 'NYC', 'SF', 'KL', 'HK' and full world city names.
    """
    q_lower = query.lower().strip()

    # 1. Check acronym / alias dictionary with word boundaries
    for alias, full_city in CITY_ALIASES.items():
        pattern = r"\b" + re.escape(alias) + r"\b"
        if re.search(pattern, q_lower):
            return full_city

    # If purely asking about Sri Lanka / current local view without a foreign city, skip
    local_indicators = ["kandy", "colombo", "sri lanka", "ceylon", "island", "our city", "this city", "here"]
    if any(loc in q_lower for loc in local_indicators) and not any(gc in q_lower for gc in MAJOR_GLOBAL_CITIES):
        return None

    # 2. Match against known major world cities
    for city in MAJOR_GLOBAL_CITIES:
        pattern = r"\b" + re.escape(city) + r"\b"
        if re.search(pattern, q_lower):
            return city

    # 3. Match conversational query patterns: "in <City>", "for <City>", "aqi of <City>"
    match = re.search(r"(?:in|for|at|of|about)\s+([a-zA-Z\s]{3,25})(?:\?|\.|\s+today|\s+now|\s+aqi|\s+weather|\s+air|$)", q_lower)
    if match:
        candidate = match.group(1).strip()
        if candidate not in ["kandy", "colombo", "sri lanka", "the city", "my city", "this place", "here", "outside", "today", "tomorrow"]:
            return candidate

    return None


def fetch_live_global_aqi(city_query: str) -> Optional[Dict]:
    """
    Fetches real-time live air quality telemetry and meteorological metrics
    for any global city worldwide using Open-Meteo Geocoding & Air Quality APIs.
    """
    try:
        encoded = urllib.parse.quote(city_query.strip())
        geo_url = f"https://geocoding-api.open-meteo.com/v1/search?name={encoded}&count=1&language=en&format=json"
        req_geo = urllib.request.Request(geo_url, headers={"User-Agent": "SentinelAQ-GlobalFetcher/2.0"})
        with urllib.request.urlopen(req_geo, timeout=4) as res_geo:
            geo_data = json.loads(res_geo.read().decode("utf-8"))
            if not geo_data.get("results"):
                return None
            place = geo_data["results"][0]
            lat = place["latitude"]
            lon = place["longitude"]
            official_name = place.get("name", city_query.capitalize())
            country = place.get("country", "")
            admin = place.get("admin1", "")

        aqi_url = f"https://air-quality-api.open-meteo.com/v1/air-quality?latitude={lat}&longitude={lon}&current=us_aqi,pm2_5,pm10,nitrogen_dioxide,ozone,carbon_monoxide"
        req_aqi = urllib.request.Request(aqi_url, headers={"User-Agent": "SentinelAQ-GlobalFetcher/2.0"})
        with urllib.request.urlopen(req_aqi, timeout=4) as res_aqi:
            aqi_data = json.loads(res_aqi.read().decode("utf-8"))
            curr = aqi_data.get("current", {})
            us_aqi = int(curr.get("us_aqi") or 0)
            status = get_aqi_category(us_aqi)

            return {
                "city": official_name,
                "admin": admin,
                "country": country,
                "lat": lat,
                "lon": lon,
                "aqi": us_aqi,
                "status": status,
                "pm25": round(float(curr.get("pm2_5") or 0), 1),
                "pm10": round(float(curr.get("pm10") or 0), 1),
                "no2": round(float(curr.get("nitrogen_dioxide") or 0), 1),
                "o3": round(float(curr.get("ozone") or 0), 1),
                "co": round(float(curr.get("carbon_monoxide") or 0), 1)
            }
    except Exception as e:
        print(f"[SentinelAI] Global telemetry fetch error for '{city_query}': {e}")
        return None


